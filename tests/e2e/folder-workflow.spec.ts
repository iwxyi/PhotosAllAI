import { copyFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { _electron as electron, expect, test, type Locator } from '@playwright/test';
import { CatalogService } from '../../apps/desktop/src/main/catalog-service';

const thumbnailSources = (images: Locator) => images.evaluateAll((elements) => elements.map((element) => {
  const url = new URL((element as HTMLImageElement).src);
  url.search = '';
  return url.href;
}));

test('configures dynamic workflows, browses stages, and refreshes external output', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'photo-workflow-e2e-'));
  const userData = path.join(root, 'user-data');
  const source = path.join(root, 'photos');
  await mkdir(path.join(userData, 'library'), { recursive: true });
  for (const folder of ['原图', '后期', '美颜', '调色', 'AI']) await mkdir(path.join(source, folder), { recursive: true });
  const fixture = path.resolve('apps/desktop/src/renderer/public/demo/portrait.jpg');
  for (const name of ['原图/DSC1.jpg', '后期/DSC1-曝光.jpg', '美颜/DSC1-美颜.jpg', '调色/DSC1-调色.jpg', 'AI/DSC1-AI-1.jpg', '原图/DSC2.jpg']) await copyFile(fixture, path.join(source, name));
  const catalog = new CatalogService(path.join(userData, 'library', 'catalog.sqlite'));
  await catalog.importFolders([source]); catalog.close();
  const app = await electron.launch({ args: [path.resolve('apps/desktop/out/main/index.js')], env: { ...process.env, PHOTOALLISAI_USER_DATA: userData } });
  try {
    const page = await app.firstWindow();
    const errors: string[] = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await expect(page.locator('.catalog-card')).toHaveCount(6);
    await page.getByRole('button', { name: '流程配置', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '流程配置', exact: true });
    await dialog.getByRole('button', { name: '新建预设' }).click();
    await dialog.getByRole('button', { name: '预览', exact: true }).click();
    await expect(dialog.getByLabel('流程匹配预览')).toContainText('2 组');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog.getByRole('status')).toHaveText('已保存');
    await page.keyboard.press('Escape');
    await expect(page.locator('.catalog-card')).toHaveCount(2);
    const group = page.locator('.catalog-card').filter({ hasText: '5 版本' });
    await group.dblclick();
    const viewer = page.getByRole('region', { name: '看图', exact: true });
    const stages = viewer.getByRole('combobox', { name: '流程阶段' });
    const versionTarget = viewer.getByRole('combobox', { name: '切换目标版本' });
    await expect(stages.locator('option')).toHaveCount(5);
    await expect(versionTarget.locator('option')).toHaveText(['RAW', '原图', '后期', '美颜', '调色', 'AI 修图', '未 AI', '首选 AI', '最新 AI']);
    await expect(versionTarget.locator('option').first()).toHaveAttribute('disabled', '');
    await expect(versionTarget.locator('hr')).toHaveCount(1);
    await versionTarget.selectOption('stage:original');
    await expect(viewer.locator('.viewer-title')).toContainText('DSC1.jpg');
    const noAiStage = await stages.locator('option').filter({ hasText: '调色' }).getAttribute('value');
    const assets = await page.evaluate(() => window.desktopApi.listCatalogAssets());
    const colorThumbnail = assets.find((asset) => asset.id === noAiStage)!.thumbnailUrl;
    const fallbackThumbnail = assets.find((asset) => asset.fileName === 'DSC2.jpg')!.thumbnailUrl;
    await versionTarget.selectOption('no-ai');
    await expect(stages).toHaveValue(noAiStage!);
    const currentSource = assets.find((asset) => asset.id === noAiStage)!.previewUrl.replace('://preview/', '://original/');
    const previousSource = assets.find((asset) => asset.fileName === 'DSC1.jpg')!.previewUrl.replace('://preview/', '://original/');
    await viewer.locator('.canvas-wrap').focus();
    await page.keyboard.down('Space');
    await expect(viewer.locator('.base-image')).toHaveAttribute('src', previousSource);
    await expect(stages).toHaveValue(noAiStage!);
    await expect(versionTarget).toHaveValue('no-ai');
    await page.keyboard.up('Space');
    await expect(viewer.locator('.base-image')).toHaveAttribute('src', currentSource);
    await expect.poll(() => thumbnailSources(viewer.locator('.thumb img'))).toEqual(expect.arrayContaining([colorThumbnail, fallbackThumbnail]));
    const colorTarget = await versionTarget.locator('option').filter({ hasText: '调色' }).getAttribute('value');
    await versionTarget.selectOption(colorTarget!);
    await expect.poll(() => thumbnailSources(viewer.locator('.thumb img'))).toEqual(expect.arrayContaining([colorThumbnail, fallbackThumbnail]));
    await versionTarget.selectOption('preferred-ai');
    await expect.poll(() => thumbnailSources(viewer.locator('.thumb img'))).toEqual(expect.arrayContaining([colorThumbnail, fallbackThumbnail]));
    await versionTarget.selectOption('no-ai');
    await expect(viewer.locator('.base-image')).toHaveClass(/is-ready/);
    const original = await stages.locator('option').filter({ hasText: '原图' }).getAttribute('value');
    await stages.selectOption(original!);
    await expect(viewer.locator('.viewer-title')).toContainText('DSC1.jpg');
    await expect(viewer.locator('.thumb')).toHaveCount(2);
    await copyFile(fixture, path.join(source, 'AI/DSC1-AI-2.jpg'));
    await expect(stages.locator('option')).toHaveCount(6, { timeout: 15000 });
    await expect(stages).toHaveValue(original!);
    for (const [width, height] of [[1440, 900], [1080, 700]]) {
      await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0]!.setSize(size[0]!, size[1]!), [width!, height!]);
      await page.screenshot({ path: `test-results/folder-workflow-${width}.png`, animations: 'disabled' });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    }
    await viewer.locator('.canvas-wrap').focus();
    await page.keyboard.press('Escape');
    await expect(page.locator('.catalog-card').filter({ hasText: '6 版本' })).toHaveCount(1, { timeout: 15000 });
    const catalogTarget = page.getByLabel('图库流程版本', { exact: true });
    await expect(catalogTarget).toHaveValue('no-ai');
    await catalogTarget.selectOption(colorTarget!);
    await expect.poll(() => thumbnailSources(page.locator('.catalog-card img'))).toEqual(expect.arrayContaining([assets.find((asset) => asset.id === noAiStage)!.thumbnailUrl, assets.find((asset) => asset.fileName === 'DSC2.jpg')!.thumbnailUrl]));
    await page.screenshot({ path: 'test-results/catalog-workflow-version.png' });
    await page.reload();
    await expect(page.locator('.catalog-card')).toHaveCount(2);
    await expect(catalogTarget).toHaveValue(colorTarget!);
    await page.getByRole('button', { name: '流程配置', exact: true }).click();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setSize(1080, 700));
    await expect(dialog.getByRole('combobox', { name: '流程配置方式' })).not.toHaveValue('off');
    await page.screenshot({ path: 'test-results/folder-workflow-editor.png', animations: 'disabled' });
    expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
    await page.keyboard.press('Escape');
    await page.getByRole('treeitem', { name: /photos 7/ }).click();
    await page.getByRole('button', { name: '流程配置', exact: true }).click();
    const mode = dialog.getByRole('combobox', { name: '流程配置方式' });
    await expect(mode).toHaveValue('inherit');
    await mode.selectOption('custom');
    await dialog.getByRole('textbox', { name: '流程名称', exact: true }).fill('此项目流程');
    await dialog.locator('summary').filter({ hasText: '1. 原图' }).click();
    await dialog.getByRole('textbox', { name: '步骤 1 正则' }).fill('(');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog.getByRole('status')).toContainText('正则');
    await dialog.getByRole('textbox', { name: '步骤 1 正则' }).fill('^原图/(?<key>[^.]+)\\.jpg$');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog.getByRole('status')).toHaveText('已保存');
    await mode.selectOption('off');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog.getByRole('status')).toHaveText('已保存');
    await page.keyboard.press('Escape');
    await expect(page.locator('.catalog-card')).toHaveCount(7);
    await page.getByRole('button', { name: '流程配置', exact: true }).click();
    await mode.selectOption('inherit');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog.getByRole('status')).toHaveText('已保存');
    await page.keyboard.press('Escape');
    await expect(page.locator('.catalog-card')).toHaveCount(2);
    expect(errors).toEqual([]);
  } finally { await app.close(); await rm(root, { recursive: true, force: true }); }
});

test('shows a matching RAW in version controls and compares the JPEG original against it', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'photo-raw-version-e2e-'));
  const userData = path.join(root, 'user-data');
  const source = path.join(root, 'photos');
  await mkdir(path.join(userData, 'library'), { recursive: true });
  await mkdir(source, { recursive: true });
  const fixture = path.resolve('apps/desktop/src/renderer/public/demo/portrait.jpg');
  await copyFile(fixture, path.join(source, 'A.jpg'));
  await copyFile(fixture, path.join(source, 'A.dng'));
  await copyFile(fixture, path.join(source, 'B.jpg'));
  const catalog = new CatalogService(path.join(userData, 'library', 'catalog.sqlite'));
  await catalog.importFolders([source]); catalog.close();
  const app = await electron.launch({ args: [path.resolve('apps/desktop/out/main/index.js')], env: { ...process.env, PHOTOALLISAI_USER_DATA: userData } });
  try {
    const page = await app.firstWindow();
    await expect(page.locator('.catalog-card')).toHaveCount(3);
    const catalogTarget = page.getByLabel('图库流程版本', { exact: true });
    await expect(catalogTarget.locator('option').first()).toBeEnabled();
    const jpeg = page.locator('.catalog-card').filter({ hasText: 'A.jpg' });
    const raw = page.locator('.catalog-card').filter({ hasText: 'A.dng' });
    const rawImage = (await thumbnailSources(raw.locator('img')))[0];
    await catalogTarget.selectOption('raw');
    await expect.poll(() => thumbnailSources(jpeg.locator('img'))).toEqual([rawImage]);
    await jpeg.dblclick();
    const viewer = page.getByRole('region', { name: '看图', exact: true });
    const target = viewer.getByRole('combobox', { name: '切换目标版本' });
    await expect(target).toHaveValue('raw');
    await expect(viewer.locator('.version-switcher button').filter({ hasText: 'RAW' })).toBeVisible();
    const rawSource = (await page.evaluate(() => window.desktopApi.listCatalogAssets())).find((asset) => asset.fileName === 'A.dng')!.previewUrl;
    await expect(viewer.locator('.base-image')).toHaveAttribute('src', rawSource);
    await expect.poll(() => thumbnailSources(viewer.locator('.thumb[data-asset-id] img').first())).toEqual([rawImage]);
    await target.selectOption('stage:original');
    const originalSource = (await page.evaluate(() => window.desktopApi.listCatalogAssets())).find((asset) => asset.fileName === 'A.jpg')!.previewUrl.replace('://preview/', '://original/');
    await viewer.locator('.canvas-wrap').focus();
    await page.keyboard.down('Space');
    await expect(viewer.locator('.base-image')).toHaveAttribute('src', rawSource);
    await page.keyboard.up('Space');
    await expect(viewer.locator('.base-image')).toHaveAttribute('src', originalSource);
    await page.keyboard.press('Escape');
    await page.getByRole('treeitem', { name: /photos/ }).click();
    expect(await page.locator('.catalog-card').count()).toBe(3);
  } finally { await app.close(); await rm(root, { recursive: true, force: true }); }
});
