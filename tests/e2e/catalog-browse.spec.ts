      for (const frame of frames) rows.set(Math.round(frame.top), [...(rows.get(Math.round(frame.top)) ?? []), frame]);
      return rows.size >= 2 && [...rows.values()].every((row) => row.every((frame) => Math.abs(frame.height - row[0]!.height) < 2));
