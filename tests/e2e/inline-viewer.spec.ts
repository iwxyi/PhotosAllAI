import path from 'node:path';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { _electron as electron, expect, test } from '@playwright/test';

test('views gallery and batch images in place and restores source state with Escape', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'photoallisai-inline-viewer-'));
  const app = await electron.launch({ args: [path.resolve('apps/desktop/out/main/index.js')], env: { ...process.env, PHOTOALLISAI_USER_DATA: directory, PHOTOALLISAI_E2E_DEMO: '1' } });
  try {
    const page = await app.firstWindow();
    await expect(page.locator('.catalog-card')).toHaveCount(6);
    expect(await page.locator('.catalog-card-image > img').first().evaluate((element) => getComputedStyle(element).objectFit)).toBe('contain');
    const errors: string[] = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setSize(1000, 600));
    await expect(page.getByRole('button', { name: '图库过滤器', exact: true })).toHaveCount(0);
    const galleryFilters = page.getByRole('group', { name: '图库过滤条件', exact: true });
    await galleryFilters.getByRole('button', { name: '至少 5 星', exact: true }).click();
    await expect(page.locator('.catalog-card')).toHaveCount(2);
    await page.getByRole('button', { name: '配置图库工具栏', exact: true }).click();
    await page.getByRole('checkbox', { name: '星级', exact: true }).click();
    await page.keyboard.press('Escape');
    await expect(galleryFilters.getByRole('group', { name: '图库星级筛选', exact: true })).toHaveCount(0);
    await expect(page.locator('.catalog-card')).toHaveCount(2);
    await galleryFilters.getByRole('button', { name: '重置图库过滤器', exact: true }).click();
    await expect(page.locator('.catalog-card')).toHaveCount(6);
    const source = page.locator('.catalog-grid');
    await source.evaluate((element) => { (element as HTMLElement).dataset.retained = 'yes'; element.scrollTop = element.scrollHeight; });
    const card = page.locator('.catalog-card').last();
    await card.click();
    const id = await card.getAttribute('data-asset-id');
    const scroll = await source.evaluate((element) => element.scrollTop);
    const tabCount = await page.getByRole('tab').count();
    await page.evaluate(() => {
      document.body.dataset.viewerUnavailableSeen = 'false';
      new MutationObserver(() => {
        if (document.querySelector('.inline-photo-viewer .preview-unavailable')) document.body.dataset.viewerUnavailableSeen = 'true';
      }).observe(document.body, { childList: true, subtree: true });
    });
    await source.focus();
    await page.keyboard.press('Enter');
    const viewer = page.getByRole('region', { name: '看图', exact: true });
    await expect(viewer).toBeVisible();
    await expect(page.getByRole('tab')).toHaveCount(tabCount);
    await expect(page.getByRole('tab', { name: '图库', exact: true })).toHaveAttribute('aria-selected', 'true');
    await expect(viewer.locator('.thumb.is-selected')).toHaveAttribute('data-asset-id', id!);
    await expect(viewer.locator('.base-image')).toHaveClass(/is-ready/);
    await expect(viewer.locator('.preview-unavailable')).toHaveCount(0);
    await expect(page.locator('body')).toHaveAttribute('data-viewer-unavailable-seen', 'false');
    const analysisDetails = page.locator('.analysis-details');
    await expect(analysisDetails.locator('.analysis-copy')).toBeHidden();
    await analysisDetails.locator('summary').click();
    await expect(analysisDetails.locator('.analysis-copy')).toBeVisible();
    await expect(analysisDetails.locator('.issue-row')).toHaveCount(2);
    await analysisDetails.locator('summary').click();
    await expect(analysisDetails.locator('.analysis-copy')).toBeHidden();
    await expect(viewer.locator('.viewer-toolbar')).toHaveCount(0);
    await expect(viewer.locator('.viewer-footer .filmstrip-toolbar')).toHaveCount(1);
    await expect.poll(() => viewer.evaluate((element) => {
      const canvas = element.querySelector('.canvas-wrap')!.getBoundingClientRect();
      const photo = element.querySelector('.photo-canvas')!.getBoundingClientRect();
      const title = element.querySelector('.viewer-title')!.getBoundingClientRect();
      return Math.min(Math.abs(canvas.width - photo.width), Math.abs(canvas.height - photo.height)) < 1
        && title.top >= canvas.top && title.bottom <= canvas.bottom;
    })).toBe(true);
    for (const [width, height] of [[1440, 900], [1000, 600]]) {
      await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0]!.setSize(size[0]!, size[1]!), [width!, height!]);
      await expect.poll(() => viewer.evaluate((element) => {
        const canvas = element.querySelector('.canvas-wrap')!.getBoundingClientRect();
        const photo = element.querySelector('.photo-canvas')!.getBoundingClientRect();
        const toolbar = element.querySelector('.viewer-footer')!.getBoundingClientRect();
        const filmstrip = element.querySelector('.filmstrip-region')!.getBoundingClientRect();
        return Math.min(Math.abs(canvas.width - photo.width), Math.abs(canvas.height - photo.height)) < 1
          && toolbar.height <= 35 && filmstrip.top >= toolbar.bottom
          && document.documentElement.scrollWidth <= window.innerWidth;
      })).toBe(true);
      await page.screenshot({ path: `test-results/inline-viewer-${width}.png` });
      await expect.poll(() => viewer.locator('.thumb').evaluateAll((elements) => elements.every((element) => {
        const image = element.querySelector('img');
        return image && image.naturalHeight > 0 && Math.abs((image.clientWidth / image.clientHeight) - image.naturalWidth / image.naturalHeight) < .025;
      })) ).toBe(true);
    }
    await page.screenshot({ path: 'test-results/inline-viewer-open.png' });
    expect(await viewer.locator('.thumb img').first().evaluate((element) => getComputedStyle(element).objectFit)).toBe('contain');
    expect(await viewer.locator('.viewer-title').evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgba(0, 0, 0, 0)');
    await expect(viewer.getByRole('button', { name: '胶片视图', exact: true })).toHaveCount(0);
    await expect(viewer.getByRole('button', { name: '网格视图', exact: true })).toHaveCount(0);
    await expect(viewer.locator('[data-tool-group="review"], [data-tool-group="export"]')).toHaveCount(0);
    await viewer.getByRole('button', { name: '至少 5 星', exact: true }).click();
    await expect(viewer.locator('.thumb')).toHaveCount(2);
    await viewer.getByLabel('星级筛选条件').selectOption('eq');
    await expect(viewer.locator('.thumb')).toHaveCount(2);
    await viewer.getByLabel('星级筛选条件').selectOption('lte');
    await expect(viewer.locator('.thumb')).toHaveCount(6);
    await viewer.getByLabel('星级筛选条件').selectOption('gte');
    await viewer.getByRole('button', { name: '筛选留用', exact: true }).click();
    await expect(viewer.locator('.thumb')).toHaveCount(0);
    await viewer.getByRole('button', { name: '筛选无旗标', exact: true }).click();
    await expect(viewer.locator('.thumb')).toHaveCount(2);
    await viewer.getByRole('button', { name: '筛选留用', exact: true }).click();
    await viewer.getByRole('button', { name: '筛选无旗标', exact: true }).click();
    await viewer.locator('.canvas-wrap').focus();
    await page.keyboard.press('ArrowRight');
    await expect(viewer.locator('.thumb.is-selected')).toHaveCount(1);
    await viewer.locator('.filmstrip').focus();
    await page.keyboard.press('ControlOrMeta+a');
    await expect(viewer.locator('.thumb.is-chosen')).toHaveCount(2);
    await page.screenshot({ path: 'test-results/viewer-filmstrip-filters.png' });
    const filmstripHeight = await viewer.locator('.filmstrip-region').evaluate((element) => element.clientHeight);
    await viewer.getByRole('button', { name: '筛选胶片文件名', exact: true }).click();
    await viewer.getByRole('textbox', { name: '筛选胶片文件名', exact: true }).blur();
    await expect(viewer.getByRole('button', { name: '筛选胶片文件名', exact: true })).toBeVisible();
    await viewer.getByRole('button', { name: '筛选胶片文件名', exact: true }).click();
    await viewer.getByRole('textbox', { name: '筛选胶片文件名', exact: true }).fill('no-such-photo');
    await expect(viewer.locator('.thumb')).toHaveCount(0);
    await expect(viewer.getByText('没有符合条件的照片')).toBeVisible();
    const emptyBounds = await viewer.getByText('没有符合条件的照片').boundingBox();
    expect(emptyBounds!.width).toBeGreaterThan(emptyBounds!.height);
    await expect(viewer.getByLabel('胶片过滤条件')).toBeVisible();
    expect(await viewer.locator('.filmstrip-region').evaluate((element) => element.clientHeight)).toBe(filmstripHeight);
    await viewer.getByRole('button', { name: '重置胶片过滤器', exact: true }).click();
    await expect(viewer.locator('.thumb')).toHaveCount(6);
    await viewer.locator('.canvas-wrap').click();
    await expect(viewer.getByRole('button', { name: '筛选胶片文件名', exact: true })).toBeVisible();
    await expect(viewer.locator('.thumb-name')).toHaveCount(0);
    await expect.poll(() => viewer.locator('.thumb').first().evaluate((element) => {
      const image = element.querySelector('img')!.getBoundingClientRect();
      const rating = element.querySelector('.thumb-rating')!.getBoundingClientRect();
      return rating.top >= image.bottom - 1;
    })).toBe(true);
    await expect(viewer.locator('.thumb-rating').first()).toBeVisible();
    await viewer.locator('.thumb:not(.is-chosen)').first().click();
    await expect(viewer.locator('.thumb.is-chosen')).toHaveCount(1);
    await viewer.locator('.thumb').first().click({ button: 'right' });
    const photoMenu = page.getByRole('menu', { name: /照片菜单/ });
    await expect(photoMenu.locator('.folder-menu-title')).toHaveCount(0);
    await expect(photoMenu.locator('.photo-menu-option-label')).toHaveText(['评分', '颜色']);
    await page.getByRole('menuitem', { name: '胶片带选项' }).click();
    await expect(page.getByRole('menuitemcheckbox', { name: '显示星级', exact: true })).toHaveAttribute('aria-checked', 'true');
    await page.getByRole('menuitemcheckbox', { name: '显示星级', exact: true }).click();
    await expect(viewer.locator('.thumb-rating')).toHaveCount(0);
    await viewer.locator('.thumb').first().click({ button: 'right' });
    await page.getByRole('menuitem', { name: '胶片带选项' }).click();
    await page.getByRole('menuitemcheckbox', { name: '显示星级', exact: true }).click();
    await expect(viewer.locator('.thumb-rating').first()).toBeVisible();
    await viewer.locator('.thumb').first().click({ button: 'right' });
    await page.getByRole('menuitem', { name: '胶片带选项' }).click();
    await page.getByRole('menuitemradio', { name: '网格', exact: true }).click();
    await expect(viewer.locator('.filmstrip')).toHaveClass(/is-grid/);
    await viewer.locator('.thumb').first().click({ button: 'right' });
    await page.getByRole('menuitem', { name: '胶片带选项' }).click();
    await page.getByRole('menuitemradio', { name: '横向胶片', exact: true }).click();
    await expect(viewer.locator('.filmstrip')).not.toHaveClass(/is-grid/);
    await viewer.locator('.viewer-footer').click({ button: 'right' });
    const toolbarSettings = page.getByRole('dialog', { name: '自定义看图工具栏' });
    await expect(toolbarSettings).toBeVisible();
    const toolbarBounds = (await viewer.locator('.viewer-footer').boundingBox())!;
    const menuBounds = (await toolbarSettings.boundingBox())!;
    expect(Math.min(Math.abs(menuBounds.y - (toolbarBounds.y + toolbarBounds.height / 2)), Math.abs(menuBounds.y + menuBounds.height - (toolbarBounds.y + toolbarBounds.height / 2)))).toBeLessThan(10);
    await toolbarSettings.getByRole('checkbox', { name: '对比', exact: true }).uncheck();
    await expect(viewer.locator('[data-toolbar-item="compare"]')).toBeHidden();
    const zoomHandle = (await toolbarSettings.getByRole('button', { name: '拖动排序缩放', exact: true }).boundingBox())!;
    const versionsHandle = (await toolbarSettings.getByRole('button', { name: '拖动排序版本切换', exact: true }).boundingBox())!;
    await page.mouse.move(zoomHandle.x + 8, zoomHandle.y + 12);
    await page.mouse.down();
    await page.mouse.move(zoomHandle.x + 8, zoomHandle.y + 4, { steps: 3 });
    await expect(toolbarSettings.locator('.is-dragging')).toHaveCount(1);
    await page.mouse.move(versionsHandle.x + 8, versionsHandle.y + 12, { steps: 12 });
    await page.waitForTimeout(100);
    await page.mouse.up();
    await page.waitForTimeout(100);
    await expect(viewer.locator('[data-toolbar-item]').first()).toHaveAttribute('data-toolbar-item', 'zoom');
    const handleBounds = (await toolbarSettings.locator('[data-layout-id="compare"] .toolbar-drag-handle').boundingBox())!;
    const targetBounds = (await toolbarSettings.locator('[data-layout-id="zoom"]').boundingBox())!;
    await page.mouse.move(handleBounds.x + handleBounds.width / 2, handleBounds.y + handleBounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(handleBounds.x + handleBounds.width / 2, handleBounds.y + handleBounds.height / 2 - 8, { steps: 3 });
    await expect(toolbarSettings.locator('.is-dragging')).toHaveCount(1);
    await page.mouse.move(handleBounds.x + handleBounds.width / 2, targetBounds.y + targetBounds.height / 2, { steps: 12 });
    await expect.poll(() => toolbarSettings.locator('.toolbar-customize-row:not(.is-dragging)').evaluateAll((elements) => elements.some((element) => (element as HTMLElement).style.transform.includes('translate')))).toBe(true);
    await page.mouse.up();
    await page.waitForTimeout(100);
    await expect(viewer.locator('[data-toolbar-item]').first()).toHaveAttribute('data-toolbar-item', 'compare');
    await toolbarSettings.getByRole('button', { name: '弹性空白', exact: true }).click();
    await expect(viewer.locator('.viewer-toolbar-spacer')).toHaveCount(2);
    await toolbarSettings.getByRole('button', { name: '分割线', exact: true }).click();
    await toolbarSettings.getByRole('button', { name: '分割线', exact: true }).click();
    await expect(viewer.locator('.viewer-toolbar-separator')).toHaveCount(2);
    await toolbarSettings.getByRole('button', { name: '移除分割线', exact: true }).first().click();
    await expect(viewer.locator('.viewer-toolbar-separator')).toHaveCount(1);
    await page.screenshot({ path: 'test-results/viewer-toolbar-customize.png' });
    await page.keyboard.press('Escape');
    await expect(toolbarSettings).toHaveCount(0);
    await expect(viewer).toBeVisible();
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('photoallisai.viewer-toolbar.v2') ?? '[]').find((entry: { id: string }) => entry.id === 'compare')?.visible)).toBe(false);
    await page.keyboard.press('Escape');
    await expect(viewer).toHaveCount(0);
    await source.focus();
    await page.keyboard.press('Enter');
    await expect(viewer.locator('[data-toolbar-item="compare"]')).toBeHidden();
    await expect(viewer.locator('.viewer-toolbar-spacer')).toHaveCount(2);
    await viewer.locator('.viewer-footer').click({ button: 'right' });
    await toolbarSettings.getByRole('button', { name: '恢复默认', exact: true }).click();
    await toolbarSettings.getByRole('button', { name: '关闭工具栏设置', exact: true }).click();
    await expect(viewer.locator('[data-toolbar-item="compare"]')).toBeVisible();
    const zoomInput = viewer.getByRole('textbox', { name: '缩放比例', exact: true });
    const fittedPercent = Number((await zoomInput.inputValue()).replace('%', ''));
    await page.getByRole('button', { name: '放大', exact: true }).click();
    await expect.poll(async () => Number((await zoomInput.inputValue()).replace('%', ''))).toBeGreaterThan(fittedPercent);
    await page.getByRole('button', { name: '适应窗口', exact: true }).click();
    await expect(zoomInput).toHaveValue(`${fittedPercent}%`);
    await page.getByRole('button', { name: '对比', exact: true }).click();
    await expect(page.getByLabel('调整原图和生成图分割线')).toBeVisible();
    await page.getByRole('button', { name: '单图', exact: true }).click();
    await page.locator('.canvas-wrap').click({ button: 'right' });
    await expect(page.getByRole('menu', { name: /照片菜单/ })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('menu', { name: /照片菜单/ })).toHaveCount(0);
    await expect(viewer).toBeVisible();
    await page.keyboard.press('ArrowLeft');
    await expect(viewer.locator('.thumb.is-selected')).not.toHaveAttribute('data-asset-id', id!);
    expect(await viewer.locator('.thumb.is-selected').evaluate((element) => {
      const style = getComputedStyle(element);
      return style.outlineStyle === 'solid' && style.outlineWidth === '2px';
    })).toBe(true);
    expect(await viewer.locator('.thumb:not(.is-selected)').evaluateAll((elements) => elements.every((element) => getComputedStyle(element).outlineStyle === 'none'))).toBe(true);
    await page.keyboard.press('Escape');
    await expect(viewer).toHaveCount(0);
    await expect(source).toHaveAttribute('data-retained', 'yes');
    expect(await source.evaluate((element) => element.scrollTop)).toBe(scroll);
    await expect(card).toHaveAttribute('aria-selected', 'true');
    await expect(source).toBeFocused();
    await card.click({ button: 'right' });
    await page.getByRole('menuitem', { name: /加入 AI 批量修图/ }).click();
    await expect(page.getByRole('tab', { name: 'AI 批量修图', exact: true })).toHaveAttribute('aria-selected', 'true');
    const queue = page.locator('.batch-queue-item').first();
    const prompt = queue.locator('textarea');
    await prompt.fill('保留原有构图，改为动漫风');
    await queue.locator('.batch-queue-source').dblclick();
    await expect(viewer).toBeVisible();
    await expect(viewer.locator('.thumb')).toHaveCount(1);
    await page.getByRole('button', { name: '关闭看图', exact: true }).click();
    await expect(prompt).toHaveValue('保留原有构图，改为动漫风');
    await expect(page.getByRole('tab', { name: '看图', exact: true })).toHaveCount(0);
    expect(errors).toEqual([]);
    await page.screenshot({ path: 'test-results/inline-viewer-source.png' });
  } finally {
    await app.close();
    await rm(directory, { recursive: true, force: true });
  }
});
